const ColorPaletteDropdown = ({ selectedPalette, setSelectedPalette }) => {
	return (
		<Box>
			<Autocomplete
				options={colorPalettes}
				getOptionLabel={option => `Palette ${colorPalettes.indexOf(option) + 1}`}
				value={selectedPalette}
				onChange={(_, newValue) => {
					if (newValue) {
						setSelectedPalette(newValue);
					}
				}}
				renderInput={params => <TextField {...params} label="Select Color Palette" />}
				renderOption={(props, option) => (
					<li {...props}>
						<Box
							sx={{
								display: 'flex',
								width: 400,
								height: 20,
							}}
						>
							{option.map(color => (
								<Box
									key={color}
									sx={{
										flex: 1,
										backgroundColor: `rgb(${color.join(',')})`,
									}}
								/>
							))}
						</Box>
					</li>
				)}
				sx={{ width: 470 }}
			/>

			{/* Selected Color Palette Display */}
			<Box
				sx={{
					mt: 2,
					display: 'flex',
					width: 470,
					height: 20,
					border: '1px solid black',
				}}
			>
				{selectedPalette.map(color => (
					<Box
						key={color}
						sx={{
							flex: 1,
							backgroundColor: `rgb(${color.join(',')})`,
						}}
					/>
				))}
			</Box>
		</Box>
	);
};

ColorPaletteDropdown.propTypes = {
	selectedPalette: PropTypes.array.isRequired,
	setSelectedPalette: PropTypes.func.isRequired,
};

export default ColorPaletteDropdown;
