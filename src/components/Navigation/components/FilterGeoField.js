export default function FilterField() {
  const [stateNav, setStateNav] = useContext(NavigationContext);
  const [fieldName, setFieldName] = React.useState(
    stateNav.fieldName ? stateNav.fieldName : null
  );

  const handleFieldChange = (value) => {
    let filter;
    if (value && value.length) {
      filter = ["match", ["get", "field"], value, true, false];
      setStateNav((stateNav) => ({ ...stateNav, fieldName: value }));
      setFieldName(value);
    } else {
      filter = null;
      setStateNav((stateNav) => ({ ...stateNav, fieldName: [] }));
    }
    setStateNav((stateNav) => ({ ...stateNav, filterField: filter }));
  };

  return (
    <Autocomplete
      ChipProps={{ color: "secondary" }}
      defaultValue={stateNav.fieldName}
      onChange={(event, newValue) => {
        handleFieldChange(newValue);
      }}
      multiple
      options={fieldList}
      renderInput={(params) => (
        <TextField
          {...params}
          variant="outlined"
          label="Field"
          placeholder=""
          fullWidth={true}
        />
      )}
      disableListWrap
    />
  );
}
