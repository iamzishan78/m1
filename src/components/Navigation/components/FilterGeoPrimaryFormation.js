export default function FilterPrimaryFormation() {
  const [stateNav, setStateNav] = useContext(NavigationContext);
  const [primaryFormationName, setPrimaryFormationName] = React.useState(
    stateNav.primaryFormationName ? stateNav.primaryFormationName : null
  );

  const handleFormationChange = (value) => {
    let filter;
    if (value && value.length) {
      filter = ["match", ["get", "primaryFormation"], value, true, false];
      setStateNav((stateNav) => ({ ...stateNav, primaryFormationName: value }));
      setPrimaryFormationName(value);
    } else {
      filter = null;
      setStateNav((stateNav) => ({ ...stateNav, primaryFormationName: [] }));
    }
    setStateNav((stateNav) => ({ ...stateNav, filterPrimaryFormation: filter }));
  };

  return (
    <Autocomplete
      ChipProps={{ color: "secondary" }}
      defaultValue={stateNav.primaryFormationName}
      onChange={(event, newValue) => {
        handleFormationChange(newValue);
      }}
      multiple
      options={primaryFormationList}
      renderInput={(params) => (
        <TextField
          {...params}
          variant="outlined"
          label="Formation"
          placeholder=""
          fullWidth={true}
        />
      )}
      disableListWrap
    />
  );
}
